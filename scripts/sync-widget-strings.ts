import { readFileSync, writeFileSync } from 'node:fs';
import { pl } from '../src/i18n/pl';
import { en } from '../src/i18n/en';
import { de } from '../src/i18n/de';
import { uk } from '../src/i18n/uk';

const check = process.argv.includes('--check');
const escapeXml = (value: string) =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"');

for (const [locale, strings] of Object.entries({ pl, en, de, uk })) {
  const w = strings.widgets;
  const values: Record<string, string> = {
    kw_next_label: w.nextTitle,
    kw_next_desc: w.picker.nextDescription,
    kw_dest_label: w.journeyTitle,
    kw_dest_desc: w.journeyDescription,
    kw_min: w.min,
    kw_trip_label: w.trackingTitle,
    kw_trip_desc: w.picker.tripDescription,
    kw_search_label: w.picker.searchTitle,
    kw_search_desc: w.picker.searchDescription,
    kw_saved_label: w.picker.placesTitle,
    kw_saved_desc: w.picker.placesDescription,
    kw_saved_empty: w.placesEmpty,
    kw_open_app: w.openApp,
    kw_search_hint: w.search,
    kw_add_place: w.addPlace,
    kw_refresh: w.refresh,
    kw_trip_empty_title: w.tripEmptyTitle,
    kw_trip_empty_body: w.tripEmptyBody,
    kw_sample_place: w.preview.home,
    kw_sample_work: w.preview.work,
    kw_sample_gym: w.preview.gym,
    kw_sample_school: w.preview.school,
    kw_sample_origin: w.preview.origin,
    kw_sample_updated: w.updated('14:30'),
    kw_sample_depart: w.departAt('14:32'),
    kw_sample_time: `5 ${w.min}`,
    kw_sample_trip_title: `${w.preview.home} → ${w.preview.work}`,
    kw_sample_status: w.onTime,
    kw_sample_phase: w.arriveIn('12'),
  };
  const xml =
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<!-- Generated by scripts/sync-widget-strings.ts from src/i18n. -->\n<resources>\n' +
    Object.entries(values)
      .map(([key, value]) => `    <string name="${key}">${escapeXml(value)}</string>`)
      .join('\n') +
    '\n</resources>\n';
  const dir = locale === 'pl' ? 'values' : `values-${locale}`;
  const path = `modules/kilometr-widgets/android/src/main/res/${dir}/kw_strings.xml`;
  if (check) {
    if (readFileSync(path, 'utf8') !== xml)
      throw new Error(`${path}: run npm run sync:widget-strings`);
  } else {
    writeFileSync(path, xml);
  }
}
console.log(check ? 'Widget translations match src/i18n.' : 'Widget translations updated.');
