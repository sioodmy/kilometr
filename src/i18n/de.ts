function formatDuration(mins: number): string {
  if (!Number.isFinite(mins) || mins <= 0) return "0 Min.";
  const rounded = Math.round(mins);
  if (rounded >= 60) {
    const h = Math.floor(rounded / 60);
    const m = rounded % 60;
    return m > 0 ? `${h}h ${m}m` : `${h}h`;
  }
  return `${rounded} Min.`;
}

