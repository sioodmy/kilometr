export interface RouteMapDocumentOptions {
  route: MapRoute | null;
  vehicle?: MapVehicle | null;
  selectedLegId?: string | null;
  /**
   * Startowa kamera mapy [lon, lat] (pierwszy kadr, zanim dane ją przesuną).
   * Default: środek trasy lub środek aktywnego miasta.
   */
  center?: [number, number] | null;
  /**
   * Bazowy URL lokalnego serwera mapy (np. `http://127.0.0.1:45999`). Gdy
   * podany, kafle i glify idą z telefonu. Silnik jest w paczce aplikacji.
   */
  offlineBase?: string | null;
  /** Etykiety POI w tle trasy. Włącza je tylko pełnoekranowa mapa szczegółów połączenia. */
  showPoi?: boolean;
  /** Marginesy widoku [top, right, bottom, left] w px. */
  padding?: [number, number, number, number];
  /** Maksymalny zoom dopasowania trasy (np. 16 dla widgetu, 17 dla mapy pełnoekranowej). */
  maxZoom?: number;
  /** Czy automatycznie dopasowywać widok po dociągnięciu geometrii każdego odcinka trasy. */
  fitOnGeometry?: boolean;
}

