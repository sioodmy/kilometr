  'function handle(msg) {',
  '  if (!msg || !msg.t) return;',
  '  if (msg.t === "vehicles") {',
  '    vehicles = Array.isArray(msg.vehicles) ? msg.vehicles : [];',
  '    selectedId = msg.selectedId || null;',
  '    drawVehicles();',
  '    return;',
  '  }',
  '  if (msg.t === "selected") {',
  '    selectedId = msg.id || null;',
  '    drawVehicleDots();',
  '    if (renderVehiclesFrame(Date.now(), true)) {',
  '      ensureMotionLoop();',
  '    }',
  '    return;',
  '  }',
  '  if (msg.t === "selectedRoute") {',
  '    selectedRoute = msg.route || null;',
  '    drawSelectedRoute();',
  '    return;',
  '  }',
  '  if (msg.t === "stops") {',
  '    stops = Array.isArray(msg.stops) ? msg.stops : [];',
  '    selectedStopId = msg.selectedStopId || null;',
  '    indexStops();',
  '    drawStops();',
  '    return;',
  '  }',
  '  if (msg.t === "disruptions") {',
  '    disruptions = Array.isArray(msg.disruptions) ? msg.disruptions : [];',
  '    selectedDisruptionId = msg.selectedDisruptionId || null;',
  '    if (typeof msg.visible === "boolean") showDisruptions = msg.visible;',
  '    drawDisruptions();',
  '    return;',
  '  }',
  '  if (msg.t === "delaySegments") {',
  '    delaySegments = Array.isArray(msg.segments) ? msg.segments : [];',
  '    selectedDelayId = msg.selectedDelayId || null;',
  '    if (typeof msg.visible === "boolean") showDelays = msg.visible;',
  '    drawDelaySegments();',
  '    return;',
  '  }',
  '  if (msg.t === "selectedStop") {',
  '    selectedStopId = msg.stopId || null;',
  '    drawSelectedStop();',
  '    return;',
  '  }',
  '  if (msg.t === "user") {',
  '    if (msg.lat === null || msg.lon === null) {',
  '      userPos = null;',
  '      drawUser();',
  '    } else if (isFinite(msg.lon) && isFinite(msg.lat)) {',
  '      userPos = [msg.lon, msg.lat];',
  '      drawUser();',
  '    }',
  '    return;',
  '  }',
  '  if (msg.t === "center") {',
