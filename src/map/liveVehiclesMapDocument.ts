function bootstrapPayload(opts: LiveVehiclesMapDocumentOptions): string {
  const base = opts.offlineBase ?? null;
  const payload = {
    style: buildMapStyle(base, { poi: false }),
    attribution: MAP_ATTRIBUTION,
    center: opts.center,
    vehicles: opts.vehicles,
    stops: opts.stops,
    selectedId: opts.selectedId,
    selectedStopId: opts.selectedStopId,
    selectedRoute: opts.selectedRoute ?? null,
    disruptions: opts.disruptions ?? [],
    selectedDisruptionId: opts.selectedDisruptionId ?? null,
    showDisruptions: opts.showDisruptions ?? true,
    delaySegments: opts.delaySegments ?? [],
    selectedDelayId: opts.selectedDelayId ?? null,
    showDelays: opts.showDelays ?? false,
    showStops: opts.showStops ?? true,
    userPos: opts.userPos,
  };
  return JSON.stringify(payload).replace(/</g, '\\u003c');
}

/** Buduje dokument HTML WebView dla mapy wszystkich pojazdów i przystanków na żywo. */
export function buildLiveVehiclesMapDocument(opts: LiveVehiclesMapDocumentOptions): string {
  return [
    '<!doctype html>',
    '<html lang="pl">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">',
    '<meta name="color-scheme" content="dark">',
    opts.mapLibreHead ?? '',
    '<title>Mapa na żywo</title>',
    '<style>' + css() + '</style>',
    '</head>',
    '<body>',
    '<div id="map"></div>',
    '<script>window.__KM_LIVE__ = ' + bootstrapPayload(opts) + ';</script>',
    '<script>' + runtime + '</script>',
    '</body>',
    '</html>',
  ].join('\n');
}
