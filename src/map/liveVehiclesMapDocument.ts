function bootstrapPayload(opts: LiveVehiclesMapDocumentOptions): string {
  const base = opts.offlineBase ?? null;
  const payload = {
    style: buildMapStyle(base, { poi: false }),
    attribution: MAP_ATTRIBUTION,
    center: opts.center,
    vehicles: opts.vehicles,
    stops: opts.stops,
    selectedId: opts.selectedId,
    selectedStopId: opts.selectedStopId,
    disruptions: opts.disruptions ?? [],
    selectedDisruptionId: opts.selectedDisruptionId ?? null,
    showDisruptions: opts.showDisruptions ?? true,
    userPos: opts.userPos,
  };
  return JSON.stringify(payload).replace(/</g, '\\u003c');
}

